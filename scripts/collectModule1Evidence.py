"""Collect numeric checks, serial timings and aperture-only comparison renders.

Run from any directory:
  python3 scripts/collectModule1Evidence.py
  python3 scripts/collectModule1Evidence.py --render --compare

The C++ renderer has no Python/Pillow dependency. Pillow is optional and used
only with --compare to arrange existing pixels into technical comparison panels.
"""
import argparse
import csv
import hashlib
import json
import platform
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = ("WSRT_simple", "WSRT_creative", "DRT_simple", "DRT_creative")
APERTURE = re.compile(r'("float apertureradius"\s+)([0-9.]+)')


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def command_output(command):
    return subprocess.check_output(command, cwd=ROOT, text=True).strip()


def save_manifest(output, data):
    (output / "manifest.json").write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def pinhole_variant(name):
    source = ROOT / "scenes" / f"{name}.pbrt"
    original = source.read_text(encoding="utf-8")
    changed, count = APERTURE.subn(lambda m: m[1] + "0.0", original)
    if count != 1:
        raise ValueError(f"{source}: expected exactly one aperture radius")
    target = source.with_name(f"{name}_pinhole.pbrt")
    header = f"# Generated by collectModule1Evidence.py from {source.name}; aperture-only A=0 control.\n"
    if target.exists() and not target.read_text(encoding="utf-8").startswith(header):
        raise FileExistsError(f"Refusing to overwrite an unfamiliar file: {target}")
    target.write_text(header + changed, encoding="utf-8")
    return target


def render(name, scene, output):
    command = [str(ROOT / "output/CGR26_renderer"), str(scene),
               "-o", str(output), "-n", name, "-q"]
    print(f"Rendering {name} serially...", flush=True)
    started = datetime.now(timezone.utc).isoformat()
    subprocess.run(command, cwd=ROOT, check=True)
    log = (output / f"{name}.log").read_text(encoding="utf-8")
    if "parse warnings=0 parse errors=0" not in log or "CGR26_renderer finished" not in log:
        raise RuntimeError(f"{name}: render has parse diagnostics or did not finish")
    if not (output / f"{name}.png").exists() or "[ERROR]" in log or "failed to write" in log:
        raise RuntimeError(f"{name}: missing image or render error")
    timing = re.search(r"frame time: ([0-9.]+) s", log)
    frame = re.search(r"(?:WSRT|DRT): (\d+)x(\d+), maxDepth=(\d+)", log)
    shapes = re.search(r"parsed scene: (\d+) shapes", log)
    spp = re.search(r"DRT: .*spp=(\d+)", log)
    if not timing or not frame or not shapes:
        raise RuntimeError(f"{name}: missing required log fields")
    row = {
        "scene": name, "resolution": f"{frame[1]}x{frame[2]}",
        "spp": int(spp[1]) if spp else 1, "max_depth": int(frame[3]),
        "primitives": int(shapes[1]), "render_seconds": float(timing[1]),
    }
    print(f"  {row['render_seconds']:.6f} s", flush=True)
    return {"command": command, "started_utc": started,
            "scene_sha256": sha256(scene), "image_sha256": sha256(output / f"{name}.png"),
            "log": f"{name}.log", "measurement": row}


def comparisons(output):
    from PIL import Image, ImageDraw, ImageFont

    # Native coordinates, top-left origin. Full frames remain at native size;
    # crops use integer nearest-neighbour enlargement without added detail.
    regions = {
        "DRT_simple": [("foreground", (65, 265, 180, 375)),
                       ("background box", (335, 115, 405, 250))],
        "DRT_creative": [("left chair", (175, 70, 243, 140)),
                         ("keyboard", (245, 165, 400, 225))],
    }
    try:
        face = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial.ttf", 16)
    except OSError:
        face = ImageFont.load_default()
    for name, crops in regions.items():
        with Image.open(output / f"{name}.png") as image:
            lens = image.convert("RGB")
        with Image.open(output / f"{name}_pinhole.png") as image:
            pinhole = image.convert("RGB")
        if lens.size != pinhole.size:
            raise ValueError(f"{name}: comparison resolution mismatch")
        scene = (ROOT / "scenes" / f"{name}.pbrt").read_text(encoding="utf-8")
        aperture = APERTURE.search(scene)[2]
        focus = re.search(r'"float focusdistance"\s+([0-9.]+)', scene)[1]
        spp = re.search(r'"integer spp"\s+(\d+)', scene)[1]
        width, height = lens.size
        gap, bar = 16, 36
        total_height = height + bar + sum((b[3] - b[1]) * 3 + bar for _, b in crops)
        panel = Image.new("RGB", (2 * width + gap, total_height), "#172033")
        draw = ImageDraw.Draw(panel)
        draw.text((8, 8), f"A={aperture}, D_scene={focus}, spp={spp}", font=face, fill="white")
        draw.text((width + gap + 8, 8), f"A=0, D_scene={focus}, spp={spp}", font=face, fill="white")
        panel.paste(lens, (0, bar))
        panel.paste(pinhole, (width + gap, bar))
        y = height + bar
        for label, bounds in crops:
            for x, image in ((0, lens), (width + gap, pinhole)):
                draw.text((x + 8, y + 8), f"{label}: {bounds}, 3x nearest", font=face, fill="white")
                crop = image.crop(bounds)
                crop = crop.resize((crop.width * 3, crop.height * 3), Image.Resampling.NEAREST)
                if crop.width > width:
                    raise ValueError(f"{name}: crop is wider than the native frame")
                panel.paste(crop, (x + (width - crop.width) // 2, y + bar))
            y += (bounds[3] - bounds[1]) * 3 + bar
        panel.save(output / f"{name}_dof_comparison.png")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--render", action="store_true", help="six serial renders, including four baseline scenes")
    parser.add_argument("--compare", action="store_true", help="arrange the aperture-control PNGs (requires Pillow)")
    args = parser.parse_args()
    output = ROOT / "output/module1-evidence"
    output.mkdir(exist_ok=True)
    subprocess.run(["make", "all", "build/module1_checks"], cwd=ROOT, check=True)
    checked = subprocess.run([str(ROOT / "build/module1_checks")], cwd=ROOT,
                             capture_output=True, text=True)
    (output / "module1_checks.log").write_text(checked.stdout + checked.stderr, encoding="utf-8")
    print(checked.stdout, end="", flush=True)
    checked.check_returncode()
    manifest_path = output / "manifest.json"
    data = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    data["checks"] = {"command": ["build/module1_checks"], "log": "module1_checks.log",
                      "collected_utc": datetime.now(timezone.utc).isoformat(),
                      "source_sha256": sha256(ROOT / "tests/module1_checks.cpp"),
                      "log_sha256": sha256(output / "module1_checks.log")}
    save_manifest(output, data)
    if args.render:
        variants = {name: pinhole_variant(name) for name in NAMES if name.startswith("DRT")}
        cpu = command_output(["sysctl", "-n", "machdep.cpu.brand_string"]) if platform.system() == "Darwin" else platform.processor()
        assets = set()
        for name in NAMES:
            text = (ROOT / "scenes" / f"{name}.pbrt").read_text(encoding="utf-8")
            assets.update(re.findall(r'"((?:meshes|textures)/[^"\n]+)"', text))
        data["render_environment"] = {"collected_utc": datetime.now(timezone.utc).isoformat(),
            "platform": platform.platform(), "cpu": cpu, "compiler": command_output(["c++", "--version"]),
            "execution": "serial, one renderer process at a time; OS background load uncontrolled",
            "renderer_sha256": sha256(ROOT / "output/CGR26_renderer"),
            "makefile_sha256": sha256(ROOT / "Makefile"),
            "asset_sha256": {asset: sha256(ROOT / "scenes" / asset) for asset in sorted(assets)}}
        data["renders"] = []
        jobs = [(name, ROOT / "scenes" / f"{name}.pbrt") for name in NAMES]
        jobs += [(f"{name}_pinhole", path) for name, path in variants.items()]
        for name, scene in jobs:
            data["renders"].append(render(name, scene, output))
            save_manifest(output, data)
        rows = [entry["measurement"] for entry in data["renders"][:4]]
        with (output / "baseline.csv").open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
    if args.compare:
        comparisons(output)
    print(f"Evidence: {output}")


if __name__ == "__main__":
    main()
